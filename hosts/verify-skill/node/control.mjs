#!/usr/bin/env node
// control.mjs: the control tool of a Node product's verify skill (docs/BUILD-PLAN.md WP4.5b). It runs one behaviour
// check of the feature map in the product's own stack, Node and Playwright, and answers by the contract aayu's
// behaviour floor holds every control tool to:
//
//   node <skill>/control.mjs check
//     stdin:  {"product", "feature", "check": {...}, "out": "<dir>", "base_url": "<url>", "root": "<repository>"}
//     stdout: {"status": "passed"|"failed"|"unreachable", "reason", "artifacts": [{"path", "kind"}]}
//
// aayu starts the app first for ui and api checks (`[verify] seed`) and passes its URL; run a check yourself with
// `aayu verify --check <feature>.<check>`. Generated by `aayu init --verify-skill` for a Node product; edit it
// freely. Steps (in the check's "steps", in order):
//
//   {"goto": "/path"}                                 load a page of the app
//   {"fill": {"label": "…", "value": "…"}}            type into the field with that label
//   {"click": {"role": "button", "name": "…"}}         click by role and accessible name, then wait for the load
//   {"expect": {"role": "heading", "name": "…"}}       that element is visible
//   {"expectText": "…"} / {"absentText": "…"}         that text is, or is not, on the page
//   {"count": {"role": "link", "within": "…", "equals": 3}}  elements of a role inside a named region
//   {"screenshot": "name.png"}                        a full-page screenshot (kind screenshot)
//   {"api": {"method", "path", "json" | "raw", "contentType", "status", "body"}}
//                                                     an HTTP call; status and a body subset are checked (api-trace)
//   {"run": ["cmd", "arg"], "exit": 0, "stdout": ["…"], "stderr": ["…"]}
//                                                     a command (a CLI, or the product's test runner), from the
//                                                     repository root; exit code and output are checked (api-trace)
//
// A check with "evidence": "recording" is recorded as video. Every check also writes actions.jsonl (each step and
// what it observed) and, for a page, aria.txt (the accessibility tree at the end). Nothing here reads the clock, so
// two runs on the same commit write the same files, video aside.
import { spawnSync } from "node:child_process";
import { createRequire } from "node:module";
import { mkdirSync, readFileSync, renameSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const [cmd] = process.argv.slice(2);
if (cmd !== "check") {
  process.stderr.write("usage: node control.mjs check < check.json (aayu verify --check runs it)\n");
  process.exit(2);
}
const input = JSON.parse(readFileSync(0, "utf8"));
const { check, out, base_url: base } = input;
const answer = (status, reason, artifacts = []) => {
  process.stdout.write(JSON.stringify({ status, reason, artifacts }) + "\n");
  process.exit(status === "passed" ? 0 : 1);
};

// A check that "requires" something the launch (`[verify] seed`) does not provide cannot be reached; the feature's
// Gotchas say what it needs. Teach this tool a precondition when the launch gains it.
if (check.requires) answer("unreachable", `the [verify] seed launch does not provide "${check.requires}"`);
if (!base && check.steps.some((s) => !s.run)) answer("unreachable", "no app URL: set [verify.environments.local] url");

function playwright() {
  for (const from of [join(input.root || process.cwd(), "package.json"), import.meta.url]) {
    try {
      return createRequire(from)("playwright"); // the product's own Playwright, else NODE_PATH's
    } catch {}
  }
  // A missing harness is not a missing precondition of the product: say so and give no result, so the floor is
  // blocked rather than passed.
  process.stderr.write("control.mjs: Playwright is not installed (add it to the product, or set NODE_PATH to a node_modules that has it, then run playwright install chromium)\n");
  process.exit(2);
}

const subset = (want, got) =>
  Object.entries(want).every(([k, v]) => (v && typeof v === "object" ? subset(v, got?.[k]) : got?.[k] === v));

mkdirSync(out, { recursive: true });
const actions = [];
const trace = [];
const artifacts = [];
let browser, ctx, page;
if (check.steps.some((s) => !s.api && !s.run)) {
  const { chromium } = playwright();
  browser = await chromium.launch();
  const video = check.evidence === "recording" ? { recordVideo: { dir: out, size: { width: 1280, height: 800 } } } : {};
  ctx = await browser.newContext({ viewport: { width: 1280, height: 800 }, ...video });
  page = await ctx.newPage();
}

const T = { timeout: 5000 };
async function step(s) {
  if (s.goto) {
    const r = await page.goto(base + s.goto, { waitUntil: "load" });
    return `HTTP ${r.status()} ${new URL(page.url()).pathname}${new URL(page.url()).search}`;
  }
  if (s.fill) {
    await page.getByLabel(s.fill.label, { exact: true }).fill(s.fill.value, T);
    return `"${s.fill.label}" = "${s.fill.value}"`;
  }
  if (s.click) {
    await page.getByRole(s.click.role, { name: s.click.name, exact: true }).click(T);
    await page.waitForLoadState("load");
    return `clicked ${s.click.role} "${s.click.name}"`;
  }
  if (s.expect) {
    await page.getByRole(s.expect.role, { name: s.expect.name, exact: true }).first().waitFor({ state: "visible", ...T });
    return `${s.expect.role} "${s.expect.name}" visible`;
  }
  if (s.expectText) {
    await page.getByText(s.expectText).first().waitFor({ state: "visible", ...T });
    return `text "${s.expectText}" visible`;
  }
  if (s.absentText) {
    const n = await page.getByText(s.absentText).count();
    if (n) throw new Error(`text "${s.absentText}" is on the page ${n} time(s)`);
    return `text "${s.absentText}" absent`;
  }
  if (s.count) {
    const n = await page.getByRole("region", { name: s.count.within, exact: true }).getByRole(s.count.role).count();
    if (n !== s.count.equals) throw new Error(`${n} ${s.count.role}(s) in "${s.count.within}", want ${s.count.equals}`);
    return `${n} ${s.count.role}(s) in "${s.count.within}"`;
  }
  if (s.screenshot) {
    await page.screenshot({ path: join(out, s.screenshot), fullPage: true });
    artifacts.push({ path: s.screenshot, kind: "screenshot" });
    return `screenshot ${s.screenshot}`;
  }
  if (s.api) {
    const a = s.api;
    const init = { method: a.method || "POST", headers: {} };
    if (a.json !== undefined || a.raw !== undefined) {
      init.headers["content-type"] = a.contentType || "application/json";
      init.body = a.raw ?? JSON.stringify(a.json);
    }
    const r = await fetch(base + a.path, init);
    const text = await r.text();
    let body = text;
    try {
      body = JSON.parse(text);
    } catch {}
    trace.push({ request: { method: init.method, path: a.path, content_type: init.headers["content-type"], body: init.body }, response: { status: r.status, body } });
    if (a.status && r.status !== a.status) throw new Error(`${init.method} ${a.path}: status ${r.status}, want ${a.status}`);
    if (a.body && !subset(a.body, body)) throw new Error(`${init.method} ${a.path}: body ${JSON.stringify(body)} lacks ${JSON.stringify(a.body)}`);
    return `${init.method} ${a.path} → ${r.status}`;
  }
  if (s.run) {
    const r = spawnSync(s.run[0], s.run.slice(1), { cwd: input.root, encoding: "utf8" });
    if (r.error) throw new Error(`${s.run[0]}: ${r.error.message}`);
    trace.push({ argv: s.run, exit: r.status, stdout: r.stdout, stderr: r.stderr });
    if (r.status !== (s.exit ?? 0)) throw new Error(`${s.run.join(" ")}: exit ${r.status}, want ${s.exit ?? 0}`);
    for (const want of s.stdout || []) if (!r.stdout.includes(want)) throw new Error(`${s.run.join(" ")}: stdout lacks "${want}"`);
    for (const want of s.stderr || []) if (!r.stderr.includes(want)) throw new Error(`${s.run.join(" ")}: stderr lacks "${want}"`);
    return `${s.run.join(" ")} → exit ${r.status}`;
  }
  throw new Error(`unknown step ${JSON.stringify(s)}`);
}

let failure = "";
try {
  for (const [i, s] of check.steps.entries()) {
    try {
      actions.push({ i, step: s, ok: true, observed: await step(s) });
    } catch (e) {
      const msg = String(e.message).split("\n")[0];
      actions.push({ i, step: s, ok: false, observed: msg });
      failure = `step ${i + 1}: ${msg}`;
      if (page) {
        await page.screenshot({ path: join(out, "failure.png"), fullPage: true });
        artifacts.push({ path: "failure.png", kind: "screenshot" });
      }
      break;
    }
  }
  if (page) {
    writeFileSync(join(out, "aria.txt"), await page.locator("body").ariaSnapshot());
    artifacts.push({ path: "aria.txt", kind: "report" });
  }
} finally {
  writeFileSync(join(out, "actions.jsonl"), actions.map((a) => JSON.stringify(a)).join("\n") + "\n");
  artifacts.push({ path: "actions.jsonl", kind: "report" });
  if (trace.length) {
    writeFileSync(join(out, "api-trace.jsonl"), trace.map((x) => JSON.stringify(x)).join("\n") + "\n");
    artifacts.push({ path: "api-trace.jsonl", kind: "api-trace" });
  }
  if (ctx) {
    const video = page.video();
    await ctx.close();
    if (video) {
      renameSync(await video.path(), join(out, "recording.webm"));
      artifacts.push({ path: "recording.webm", kind: "recording" });
    }
  }
  if (browser) await browser.close();
}
// A failing check keeps its captures for the person reading the pack, but a failure screenshot is never evidence.
answer(failure ? "failed" : "passed", failure, failure ? artifacts.map((a) => (a.path === "failure.png" ? { ...a, kind: "report" } : a)) : artifacts);
