// Command control is the control tool of a Go product's verify skill
// (docs/BUILD-PLAN.md WP4.5b): it runs one behaviour check of the feature map
// in the product's own stack, Go, and answers by the contract aayu's behaviour
// floor holds every control tool to:
//
//	go run ./<skill>/control check
//	  stdin:  {"product", "feature", "check": {...}, "out": "<dir>", "base_url": "<url>", "root": "<repository>"}
//	  stdout: {"status": "passed"|"failed"|"unreachable", "reason", "artifacts": [{"path", "kind"}]}
//
// Steps, in order; each check runs in a fresh working directory of its own:
//
//	{"build": "./cmd/tool"}             build a command from the checkout; later run steps call it by its name
//	{"run": ["tool", "add", "x"], "exit": 0, "stdout": ["…"], "stderr": ["…"], "env": {"K": "v"}}
//	                                    run a built command (or one on PATH); the exit code must match and each
//	                                    string must appear in stdout or stderr
//	{"test": "TestName", "package": "./pkg"}
//	                                    run one test with the product's test framework (go test); it must pass
//	{"api": {"method", "path", "json", "status", "body"}}
//	                                    an HTTP call to base_url; the status and a body subset are checked
//
// Every check writes transcript.jsonl (kind api-trace): each command, test, or call, and what it returned. A
// harness that cannot do its part (the build fails, a command cannot start) gives no result, so the floor is
// blocked, never passed. Generated by `aayu init --verify-skill` for a Go product; edit it freely.
package main

import (
	"bytes"
	"encoding/json"
	"errors"
	"fmt"
	"io"
	"net/http"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
)

type step struct {
	Build   string            `json:"build"`
	Run     []string          `json:"run"`
	Exit    int               `json:"exit"`
	Stdout  []string          `json:"stdout"`
	Stderr  []string          `json:"stderr"`
	Env     map[string]string `json:"env"`
	Test    string            `json:"test"`
	Package string            `json:"package"`
	API     *struct {
		Method string         `json:"method"`
		Path   string         `json:"path"`
		JSON   any            `json:"json"`
		Status int            `json:"status"`
		Body   map[string]any `json:"body"`
	} `json:"api"`
}

type input struct {
	Check struct {
		ID       string `json:"id"`
		Requires string `json:"requires"`
		Steps    []step `json:"steps"`
	} `json:"check"`
	Out     string `json:"out"`
	BaseURL string `json:"base_url"`
	Root    string `json:"root"`
}

type artifact struct {
	Path string `json:"path"`
	Kind string `json:"kind"`
}

// tmp is the check's scratch directory, removed on every exit.
var tmp string

func answer(status, reason string, arts []artifact) {
	_ = os.RemoveAll(tmp)
	b, _ := json.Marshal(map[string]any{"status": status, "reason": reason, "artifacts": arts})
	fmt.Println(string(b))
	if status != "passed" {
		os.Exit(1)
	}
	os.Exit(0)
}

// harness reports that the control tool itself could not do its part.
func harness(format string, args ...any) {
	_ = os.RemoveAll(tmp)
	fmt.Fprintf(os.Stderr, "control: "+format+"\n", args...)
	os.Exit(2)
}

func subset(want map[string]any, got any) bool {
	m, ok := got.(map[string]any)
	if !ok {
		return false
	}
	for k, v := range want {
		if w, ok := v.(map[string]any); ok {
			if !subset(w, m[k]) {
				return false
			}
		} else if fmt.Sprint(m[k]) != fmt.Sprint(v) {
			return false
		}
	}
	return true
}

func main() {
	if len(os.Args) != 2 || os.Args[1] != "check" {
		harness("usage: control check < check.json (aayu verify --check runs it)")
	}
	var in input
	if err := json.NewDecoder(os.Stdin).Decode(&in); err != nil {
		harness("the check on stdin: %v", err)
	}
	if in.Check.Requires != "" {
		answer("unreachable", "this product's launch does not provide "+in.Check.Requires, nil)
	}
	var err error
	if tmp, err = os.MkdirTemp("", "verify-control-"); err != nil {
		harness("%v", err)
	}
	bin, work := filepath.Join(tmp, "bin"), filepath.Join(tmp, "work")
	for _, d := range []string{bin, work} {
		if err := os.MkdirAll(d, 0o755); err != nil {
			harness("%v", err)
		}
	}

	var transcript bytes.Buffer
	enc := json.NewEncoder(&transcript)
	arts := []artifact{{Path: "transcript.jsonl", Kind: "api-trace"}}
	save := func() {
		if err := os.WriteFile(filepath.Join(in.Out, "transcript.jsonl"), transcript.Bytes(), 0o644); err != nil {
			harness("%v", err)
		}
	}
	fail := func(i int, format string, args ...any) {
		save()
		answer("failed", fmt.Sprintf("step %d: ", i+1)+fmt.Sprintf(format, args...), arts)
	}
	for i, s := range in.Check.Steps {
		switch {
		case s.Build != "":
			b := exec.Command("go", "build", "-o", filepath.Join(bin, filepath.Base(s.Build)), s.Build)
			b.Dir = in.Root
			if out, err := b.CombinedOutput(); err != nil {
				harness("go build %s: %v\n%s", s.Build, err, out)
			}
		case s.Run != nil:
			name := s.Run[0]
			if p := filepath.Join(bin, name); fileExists(p) {
				name = p
			}
			cmd := exec.Command(name, s.Run[1:]...)
			cmd.Dir = work
			cmd.Env = os.Environ()
			for k, v := range s.Env {
				cmd.Env = append(cmd.Env, k+"="+v)
			}
			var stdout, stderr bytes.Buffer
			cmd.Stdout, cmd.Stderr = &stdout, &stderr
			code := 0
			if err := cmd.Run(); err != nil {
				var ee *exec.ExitError
				if !errors.As(err, &ee) {
					harness("%s: %v", s.Run[0], err)
				}
				code = ee.ExitCode()
			}
			_ = enc.Encode(map[string]any{"argv": s.Run, "exit": code, "stdout": stdout.String(), "stderr": stderr.String()})
			line := strings.Join(s.Run, " ")
			if code != s.Exit {
				fail(i, "%s: exit %d, want %d (stderr %q)", line, code, s.Exit, strings.TrimSpace(stderr.String()))
			}
			for _, want := range s.Stdout {
				if !strings.Contains(stdout.String(), want) {
					fail(i, "%s: stdout %q lacks %q", line, stdout.String(), want)
				}
			}
			for _, want := range s.Stderr {
				if !strings.Contains(stderr.String(), want) {
					fail(i, "%s: stderr %q lacks %q", line, stderr.String(), want)
				}
			}
		case s.Test != "":
			cmd := exec.Command("go", "test", "-count=1", "-json", "-run", "^"+s.Test+"$", s.Package)
			cmd.Dir = in.Root
			out, err := cmd.Output()
			passed := false
			for _, line := range bytes.Split(out, []byte("\n")) {
				var ev struct{ Action, Test, Output string }
				if json.Unmarshal(line, &ev) != nil || ev.Test != s.Test || ev.Action == "output" && !strings.Contains(ev.Output, ".go:") {
					continue // timings vary from run to run; a failure's file:line message is kept
				}
				if ev.Action == "pass" {
					passed = true
				}
				_ = enc.Encode(map[string]any{"test": s.Test, "package": s.Package, "action": ev.Action, "output": ev.Output})
			}
			if err != nil || !passed {
				fail(i, "go test -run %s %s did not pass", s.Test, s.Package)
			}
		case s.API != nil:
			if in.BaseURL == "" {
				answer("unreachable", "no app URL: set [verify.environments.local] url", nil)
			}
			method := s.API.Method
			if method == "" {
				method = http.MethodPost
			}
			var body io.Reader
			if s.API.JSON != nil {
				b, _ := json.Marshal(s.API.JSON)
				body = bytes.NewReader(b)
			}
			req, err := http.NewRequest(method, strings.TrimRight(in.BaseURL, "/")+s.API.Path, body)
			if err != nil {
				harness("%v", err)
			}
			if body != nil {
				req.Header.Set("Content-Type", "application/json")
			}
			resp, err := http.DefaultClient.Do(req)
			if err != nil {
				fail(i, "%s %s: %v", method, s.API.Path, err)
			}
			raw, _ := io.ReadAll(resp.Body)
			_ = resp.Body.Close()
			var got any = string(raw)
			_ = json.Unmarshal(raw, &got)
			_ = enc.Encode(map[string]any{"request": map[string]any{"method": method, "path": s.API.Path, "json": s.API.JSON}, "response": map[string]any{"status": resp.StatusCode, "body": got}})
			if s.API.Status != 0 && resp.StatusCode != s.API.Status {
				fail(i, "%s %s: status %d, want %d", method, s.API.Path, resp.StatusCode, s.API.Status)
			}
			if s.API.Body != nil && !subset(s.API.Body, got) {
				fail(i, "%s %s: body %s lacks %v", method, s.API.Path, raw, s.API.Body)
			}
		default:
			fail(i, "unknown step")
		}
	}
	save()
	answer("passed", "", arts)
}

func fileExists(p string) bool {
	st, err := os.Stat(p)
	return err == nil && !st.IsDir()
}
