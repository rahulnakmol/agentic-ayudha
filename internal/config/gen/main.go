func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "config/gen:", err)
		os.Exit(1)
	}
}

func run() error {
	if _, err := os.Stat("go.mod"); err != nil {
		return errors.New("run from the repository root (go generate ./... does this)")
	}
	var doc map[string]any
	if err := toml.Unmarshal(config.DefaultsTOML, &doc); err != nil {
		return fmt.Errorf("internal/config/defaults.toml: %w", err)
	}
	values := map[string]any{}
	flatten("", doc, values)

	out, err := render(values)
	if err != nil {
		return err
	}
	if old, err := os.ReadFile("CONSTRAINTS.md"); err == nil && string(old) == out {
		return nil
	}
	return os.WriteFile("CONSTRAINTS.md", []byte(out), 0o644)
}

func flatten(prefix string, m map[string]any, out map[string]any) {
	for k, v := range m {
		key := k
		if prefix != "" {
			key = prefix + "." + k
		}
		if sub, ok := v.(map[string]any); ok {
			flatten(key, sub, out)
			continue
		}
		out[key] = v
	}
}

func render(values map[string]any) (string, error) {
	var b strings.Builder
	b.WriteString("<!-- " + generatedBy + " -->\n")
	b.WriteString(`
# Constraints

The defaults every product repository starts with. Generated from ` + "`internal/config/defaults.toml`" + `, the
configuration embedded in the binary, by ` + "`go generate ./...`" + `; do not edit by hand. A repository changes them in
` + "`.aayudha/config.toml`" + `, which is a protected path. The Quality Architect seat owns these thresholds; the AI Native
Engineer executes ` + "`verify`" + ` against them. Changing a default regenerates this file, which is also a protected path.

Source: a WP means docs/BUILD-PLAN.md fixes the value there; "` + proposed + `" means the plan names the key but not
its value, and WP0.5 chose it.
`)
	var problems []string
	for _, s := range sections {
		fmt.Fprintf(&b, "\n## %s\n\n| Key | Default | Meaning | Source |\n|---|---|---|---|\n", s.heading)
		seen := map[string]bool{}
		for _, r := range s.rows {
			seen[r.key] = true
			v, ok := values[r.key]
			if !ok {
				problems = append(problems, "documented key missing from defaults.toml: "+r.key)
				continue
			}
			fmt.Fprintf(&b, "| `%s` | `%s` | %s | %s |\n", r.key, literal(v), cell(r.meaning), r.source)
		}
		for _, k := range sortedKeys(values) {
			for _, root := range s.roots {
				if strings.HasPrefix(k, root+".") && !seen[k] {
					problems = append(problems, "key in defaults.toml has no row in internal/config/gen: "+k)
				}
			}
		}
		if s.note != "" {
			b.WriteString("\n" + s.note + "\n")
		}
	}
	if len(problems) > 0 {
		return "", errors.New(strings.Join(problems, "; "))
	}
	return b.String(), nil
}

// literal renders a decoded TOML value back in TOML syntax.
func literal(v any) string {
	switch x := v.(type) {
	case string:
		return strconv.Quote(x)
	case float64:
		s := strconv.FormatFloat(x, 'f', -1, 64)
		if !strings.ContainsAny(s, ".eE") {
			s += ".0"
		}
		return s
	case []any:
		parts := make([]string, len(x))
		for i, e := range x {
			parts[i] = literal(e)
		}
		return "[" + strings.Join(parts, ", ") + "]"
	default:
		return fmt.Sprint(x)
	}
}

func cell(s string) string { return strings.ReplaceAll(s, "|", `\|`) }

func sortedKeys(m map[string]any) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}
