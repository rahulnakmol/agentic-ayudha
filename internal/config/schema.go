package config

import (
	"bytes"
	"encoding/json"

	"github.com/invopop/jsonschema"
)

// SchemaPath is where go generate writes the config JSON Schema (drift-checked in CI).
const SchemaPath = "internal/config/schema.json"

// Schema returns the JSON Schema of a config file, generated from the Config
// structs. Editors can use it through a `#:schema` comment.
func Schema() ([]byte, error) {
	r := &jsonschema.Reflector{
		FieldNameTag:               "koanf",
		RequiredFromJSONSchemaTags: true, // nothing is required: every layer is partial
		DoNotReference:             true,
	}
	s := r.Reflect(&Config{})
	s.ID = "https://github.com/rahulnakmol/agentic-ayudha/internal/config/schema.json"
	s.Title = "aayudha config"
	s.Description = "Code generated by go generate (internal/verbs/gen) from internal/config; DO NOT EDIT. Layered: user, .aayudha/config.toml, .aayudha/config.local.toml, AAYU_<SECTION>__<KEY>, --set."
	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetEscapeHTML(false)
	enc.SetIndent("", "  ")
	if err := enc.Encode(s); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}

// JSONSchemaExtend describes [models]: the gateway table plus one table per
// lane, each keyed by host. The lanes are a ",remain" map that reflection cannot see.
func (Models) JSONSchemaExtend(s *jsonschema.Schema) {
	gw, _ := s.Properties.Get("gateway")
	choice := (&jsonschema.Reflector{FieldNameTag: "koanf", DoNotReference: true, RequiredFromJSONSchemaTags: true}).Reflect(&ModelChoice{})
	choice.Version, choice.ID = "", ""
	s.Properties = jsonschema.NewProperties()
	s.Properties.Set("gateway", gw)
	s.AdditionalProperties = &jsonschema.Schema{
		Type:                 "object",
		Description:          "[models.<lane>.<host>]: lane and host IDs from the verb registry.",
		AdditionalProperties: choice,
	}
}
