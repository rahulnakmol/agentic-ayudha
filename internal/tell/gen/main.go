// Command gen renders the docs guide's diagrams: each docs/guide/img/<name>.diagram
// (the line-based format of internal/brief, WP7.4) becomes <name>.svg beside it,
// which the guide pages show and `aayu tell docs --site` copies into the site
// (WP8.2). It is run from the repository root by `go generate ./...` through the
// directive in embed.go; CI fails on drift, and an SVG without a source is deleted.
package main

import (
	"bytes"
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/rahulnakmol/agentic-ayudha/internal/brief"
)

const dir = "docs/guide/img"

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "gen:", err)
		os.Exit(1)
	}
}

func run() error {
	if _, err := os.Stat("go.mod"); err != nil {
		return errors.New("run from the repository root (go generate ./... does this)")
	}
	srcs, err := filepath.Glob(filepath.Join(dir, "*.diagram"))
	if err != nil {
		return err
	}
	want := map[string]bool{}
	for _, src := range srcs {
		b, err := os.ReadFile(src)
		if err != nil {
			return err
		}
		d, err := brief.ParseDiagram(string(b))
		if err != nil {
			return fmt.Errorf("%s: %w", src, err)
		}
		if d.Title == "" {
			return fmt.Errorf("%s: needs a title: line (the image's accessible name)", src)
		}
		name := strings.TrimSuffix(filepath.Base(src), ".diagram")
		out := filepath.Join(dir, name+".svg")
		want[out] = true
		svg := "<!-- Code generated by go generate (internal/tell/gen) from " + name + ".diagram; DO NOT EDIT. -->\n" +
			d.SVG(name, d.Title, false) + "\n"
		if old, err := os.ReadFile(out); err == nil && bytes.Equal(old, []byte(svg)) {
			continue
		}
		if err := os.WriteFile(out, []byte(svg), 0o644); err != nil {
			return err
		}
	}
	stale, err := filepath.Glob(filepath.Join(dir, "*.svg"))
	if err != nil {
		return err
	}
	for _, f := range stale {
		if !want[f] {
			if err := os.Remove(f); err != nil {
				return err
			}
		}
	}
	return nil
}
