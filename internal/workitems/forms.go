package workitems

import (
	"bytes"
	"encoding/json"
	"fmt"
	"strings"
)

// FormOptions vary a form by repository owner.
type FormOptions struct {
	// IssueTypes sets the form's `type:` key so issues get the GitHub issue type.
	// Only valid when the owner is an organization with these types (R1); on a
	// personal repository the type:<id> label is the type.
	IssueTypes bool
}

// FormFile is the file name of a type's issue form under .github/ISSUE_TEMPLATE/.
// The aayudha- prefix keeps it apart from a product's own templates.
func FormFile(t Type) string { return "aayudha-" + t.ID + ".yml" }

// Form renders the GitHub issue form for t (WP2.2). It holds the Create fields,
// plus the Ready fields for types that are authored rather than filed as intake;
// Complete fields are added by the verbs that complete the item. Fields required
// at Create are required by the form. Label-held fields (Priority, Effort, Risk,
// Health, Horizon) are not body fields: their single home is the label.
func Form(t Type, opts FormOptions) []byte {
	var b bytes.Buffer
	w := func(format string, args ...any) { fmt.Fprintf(&b, format, args...) }
	w("# Code generated by go generate (internal/workitems/gen); DO NOT EDIT.\n")
	w("# aayudha work-item schema v%d, type %s (docs/BUILD-PLAN.md WP2.1-WP2.2).\n", SchemaVersion, t.ID)
	w("name: %s\n", q(t.Name))
	w("description: %s\n", q(t.Description))
	w("title: %s\n", q(t.Name+": "))
	labels := []string{"type:" + t.ID, "status:backlog"}
	if t.Intake {
		labels = append(labels, LabelIntake)
	}
	w("labels: [%s]\n", strings.Join(qs(labels), ", "))
	if opts.IssueTypes {
		w("type: %s\n", q(t.Name))
	}
	w("body:\n")
	w("  - type: markdown\n    attributes:\n      value: %s\n", q(intro(t)))
	for _, s := range t.Sections {
		if s.Stage == StageComplete || (t.Intake && s.Stage != StageCreate) {
			continue
		}
		for _, f := range s.Fields {
			formField(w, f)
		}
	}
	return b.Bytes()
}

func intro(t Type) string {
	if t.Intake {
		return t.Description + " Describe it in your own words; a maintainer classifies it."
	}
	var s strings.Builder
	s.WriteString(t.Description)
	if len(t.Parents) > 0 {
		fmt.Fprintf(&s, " Add it as a sub-issue of its parent %s.", strings.Join(t.Parents, " or "))
	}
	s.WriteString(" Set Priority, Effort, Risk, Health, and Horizon with the `priority:`, `effort:`, `risk:`, `health:`, and `horizon:` labels; they are not form fields.")
	if t.Effort {
		s.WriteString(" Effort is required at Ready, and `effort:XL` blocks Ready: slice it first.")
	}
	s.WriteString(" Fields left blank here can be filled in before `aayu ready`.")
	return s.String()
}

func formField(w func(string, ...any), f Field) {
	typ := "textarea"
	switch f.Kind {
	case KindText:
		typ = "input"
	case KindEnum:
		typ = "dropdown"
	}
	w("  - type: %s\n    id: %s\n    attributes:\n      label: %s\n", typ, f.ID, q(f.Label))
	if f.Description != "" {
		w("      description: %s\n", q(f.Description))
	}
	if f.Placeholder != "" && typ != "dropdown" {
		w("      placeholder: %s\n", q(f.Placeholder))
	}
	if typ == "dropdown" {
		w("      options: [%s]\n", strings.Join(qs(f.Options), ", "))
	}
	w("    validations:\n      required: %t\n", f.RequiredAt == StageCreate)
}

// q quotes s as a YAML double-quoted scalar (JSON string syntax is valid YAML).
func q(s string) string {
	var b bytes.Buffer
	enc := json.NewEncoder(&b)
	enc.SetEscapeHTML(false)
	_ = enc.Encode(s)
	return strings.TrimSuffix(b.String(), "\n")
}

func qs(ss []string) []string {
	out := make([]string, len(ss))
	for i, s := range ss {
		out[i] = q(s)
	}
	return out
}
