// stagePages are the guide pages that tell each journey stage (docs/guide).
var stagePages = map[verbs.StageID]string{
	verbs.StageSetup: "start.md", verbs.StageShape: "journey-1-shape.md", verbs.StageBreakDown: "journey-2-break-down.md",
	verbs.StageReady: "journey-3-ready.md", verbs.StageDesign: "journey-4-build.md#if-your-story-has-a-screen",
	verbs.StageBuild: "journey-4-build.md", verbs.StageProve: "journey-5-prove.md", verbs.StageShip: "journey-6-ship.md",
	verbs.StageRelease: "journey-7-release.md", verbs.StageLearn: "journey-8-learn.md", verbs.StageExplain: "journey-9-explain.md",
	verbs.StageOperate: "when-to-use-what.md#something-broke-in-production",
}

// genVerbMap writes every verb under its journey stage, linked to its skill.
func genVerbMap() error {
	const path = "docs/guide/when-to-use-what.md"
	b, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	var m strings.Builder
	fmt.Fprintf(&m, "| Stage | Verb | What it does |\n|---|---|---|\n")
	for _, st := range verbs.Stages {
		page, ok := stagePages[st.ID]
		if !ok {
			return fmt.Errorf("%s: stage %s has no guide page", path, st.ID)
		}
		first := true
		for _, c := range verbs.Verbs {
			if c.Stage != st.ID {
				continue
			}
			stage := ""
			if first {
				stage, first = fmt.Sprintf("[%s](%s)", st.Title, page), false
			}
			name := code(c.Name)
			if c.Has(verbs.SurfaceSkill) {
				name = fmt.Sprintf("[%s](../../%s/%s/SKILL.md)", name, skillsDir, c.Name)
			}
			fmt.Fprintf(&m, "| %s | %s | %s |\n", stage, name, cell(c.Summary))
		}
	}
	s, err := replaceRegion(path, string(b), "verb-map", m.String())
	if err != nil {
		return err
	}
	return writeFile(path, []byte(s))
}

// ---- LAYERS.md -------------------------------------------------------------

func genLayers() error {
	var b strings.Builder
	b.WriteString(mdHeader)
	b.WriteString(`
# Layers

Generated from ` + code("internal/verbs/registry.go") + ` by ` + code("go generate ./...") + `. A changed path belongs to the
layer whose glob matches it; ` + code("slice") + ` and the screen-reader floor compute story footprints from these globs.
Each layer has exactly one owner seat; its charter is ` + code("seats/<seat>/CHARTER.md") + `.

| Layer | Name | Owner seat | Paths |
|---|---|---|---|
`)
	for _, l := range verbs.LayerTable {
		globs := make([]string, len(l.Paths))
		for i, p := range l.Paths {
			globs[i] = code(p)
		}
		fmt.Fprintf(&b, "| %s | %s | %s | %s |\n", l.ID, cell(l.Name), verbs.SeatName(l.Owner), strings.Join(globs, "<br>"))
	}
	return writeFile("LAYERS.md", []byte(b.String()))
}

// ---- docs/RACI.md ----------------------------------------------------------

func genRACI() error {
	var b strings.Builder
	b.WriteString(mdHeader)
	b.WriteString(`
# RACI

Generated from ` + code("internal/verbs/registry.go") + ` and ` + code("internal/verbs/raci.go") + ` by ` + code("go generate ./...") + ` (WP5.1).
Every verb has exactly one Accountable seat (A). The Responsible party (R) is always that seat's agent twin working in
the verb's model lane, with the seat's paired human when it has one; the seat that owns the verb's thresholds or policy
may differ (the AI Native Engineer executes ` + code("verify") + ` against floors the Quality Architect owns in
` + code("CONSTRAINTS.md") + `; the Engineering Manager owns the ` + code("inspect") + ` policy that the review lane executes).
Consulted seats (C) are asked before the verb acts and Informed seats (I) are told after. Every layer has exactly one
owner seat (LAYERS.md). The registry lint (` + code("verbs.LintRACI") + `) fails generation otherwise. Each seat runs
solo (agent only) or paired (agent twin plus a human): ` + code("[seats.<name>]") + `, set by ` + code("aayu seat add|remove") + `.
Charters: ` + code("seats/<seat>/CHARTER.md") + `.

## Verbs

| Verb | A | R (executes) | Owns thresholds / policy | C | I | Layers | Identity | Model calling | MCP |
|---|---|---|---|---|---|---|---|---|---|
`)
	names := func(ids []verbs.SeatID) string {
		if len(ids) == 0 {
			return "—"
		}
		out := make([]string, len(ids))
		for i, id := range ids {
			out[i] = verbs.SeatName(id)
		}
		return strings.Join(out, ", ")
	}
	for _, c := range verbs.Verbs {
		r := verbs.RACI[c.Name]
		fmt.Fprintf(&b, "| %s | %s | %s twin, %s lane | %s | %s | %s | %s | %s | %s | %s |\n", code(c.Name), verbs.SeatName(c.Seat),
			verbs.SeatName(c.Seat), c.Lane, verbs.SeatName(verbs.PolicyOwner(c)), cell(names(r.Consulted)), cell(names(r.Informed)),
			c.Layers, c.Identity, cell(mode(c)), c.Exposure)
	}

	b.WriteString(`
Model calling: ` + code("none") + ` is deterministic; ` + code("host") + ` means the host's model reasons inside the skill;
` + code("direct") + ` means the binary calls a model itself; ` + code("hybrid") + ` is host reasoning plus a direct pass
(ground rule 5). MCP: ` + code("read") + ` is exposed by default, ` + code("write") + ` only with ` + code("[mcp] expose_writes = true") + `,
` + code("never") + ` is human-only or admin (WP3.3).

## Plumbing commands

| Command | Accountable | Identity |
|---|---|---|
`)
	for _, c := range verbs.Plumbing {
		fmt.Fprintf(&b, "| %s | %s | %s |\n", code(c.Name), verbs.SeatName(c.Seat), c.Identity)
	}

	b.WriteString("\n## Seats\n\n| Seat | Slug |\n|---|---|\n")
	for _, s := range verbs.Seats {
		fmt.Fprintf(&b, "| %s | %s |\n", s.Name, code(string(s.ID)))
	}

	b.WriteString(`
## Model lanes

Settled defaults per host. Configuration (` + code("[models.<lane>.<host>]") + `, WP1.2) overrides them; the model gateway
resolves them (WP1.6). Model IDs are as the AI gateway lists them; the family belongs to the model, not the endpoint.
Cursor cannot run the openai family, so a GPT model configured for Cursor falls back to the lane's Cursor default.
When the binary calls a model itself and the host's default is a host-managed mode, it uses the Claude Code default.

` + verbs.ReviewerFamilyRule + `

| Lane | Host | Default | Model ID | Family | Escalation / alternative |
|---|---|---|---|---|---|
`)
	for _, l := range verbs.Lanes {
		for _, d := range l.Defaults {
			h, _ := verbs.FindHost(d.Host)
			model := d.Model
			if d.ContextTokens > 0 {
				model += fmt.Sprintf(" (%dk context)", d.ContextTokens/1000)
			}
			var extra []string
			if d.Escalation != "" {
				esc := "escalation: " + d.Escalation
				if d.EscalationID != "" {
					esc += " (" + code(d.EscalationID) + ")"
				}
				extra = append(extra, esc)
			}
			if d.Alternative != "" {
				extra = append(extra, "or "+d.Alternative)
			}
			if d.Note != "" {
				extra = append(extra, "note: "+d.Note)
			}
			alt := "—"
			if len(extra) > 0 {
				alt = strings.Join(extra, "; ")
			}
			name := code(string(l.ID))
			if l.Adversarial {
				name += " (adversarial)"
			}
			id := "host-managed"
			if d.ID != "" {
				id = code(d.ID)
			}
			fmt.Fprintf(&b, "| %s | %s | %s | %s | %s | %s |\n", name, h.Name, cell(model), id, d.Family, cell(alt))
		}
	}
	return writeFile("docs/RACI.md", []byte(b.String()))
}

// ---- seats/<seat>/CHARTER.md and AGENTS.md ----------------------------------

func genCharters() error {
	entries, err := os.ReadDir("seats")
	if err != nil {
		return err
	}
	want := map[string]bool{}
	for _, st := range verbs.Seats {
		want[string(st.ID)] = true
		path := filepath.Join("seats", string(st.ID), "CHARTER.md")
		old, err := os.ReadFile(path)
		if err != nil {
			return fmt.Errorf("every seat needs a hand-authored charter with a generated region (WP5.1): %w", err)
		}
		s, err := replaceRegion(path, string(old), "raci", seats.CharterRegion(st.ID))
		if err != nil {
			return err
		}
		if err := writeFile(path, []byte(s)); err != nil {
			return err
		}
	}
	for _, e := range entries {
		if e.IsDir() && !want[e.Name()] {
			return fmt.Errorf("seats/%s is not one of the twelve registry seats", e.Name())
		}
	}
	return nil
}

