// Command gen regenerates every artifact derived from the verb registry
// (internal/verbs/registry.go, docs/BUILD-PLAN.md ground rule 4). It is run from
// the repository root by `go generate ./...` through the directive in embed.go.
//
// Outputs:
//   - README.md: only the regions between the BEGIN/END GENERATED markers
//   - LAYERS.md and docs/RACI.md: whole files
//   - skills/<verb>/SKILL.md: only the YAML frontmatter; the body is hand-authored
//   - internal/mcp/schemas/<verb>.json: whole files; stale schemas are deleted
//   - internal/config/schema.json: the config JSON Schema, from the config structs (WP1.2)
//
// Output is deterministic so CI can fail on any difference after regeneration.
package main

import (
	"bytes"
	"encoding/json"
	"errors"
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"strings"

	"github.com/rahulnakmol/agentic-ayudha/internal/config"
	"github.com/rahulnakmol/agentic-ayudha/internal/verbs"
)

const (
	generatedBy = "Code generated by go generate (internal/verbs/gen); DO NOT EDIT."
	mdHeader    = "<!-- " + generatedBy + " -->\n"
	schemaDir   = "internal/mcp/schemas"
	skillsDir   = "skills"
)

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "gen:", err)
		os.Exit(1)
	}
}

func run() error {
	if _, err := os.Stat("go.mod"); err != nil {
		return errors.New("run from the repository root (go generate ./... does this)")
	}
	steps := []func() error{genReadme, genLayers, genRACI, genSkills, genSchemas, genConfigSchema}
	for _, step := range steps {
		if err := step(); err != nil {
			return err
		}
	}
	return nil
}

// writeFile writes data to path only when it differs, creating parent directories.
func writeFile(path string, data []byte) error {
	if old, err := os.ReadFile(path); err == nil && bytes.Equal(old, data) {
		return nil
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	return os.WriteFile(path, data, 0o644)
}

// cell escapes a value for a markdown table cell.
func cell(s string) string { return strings.ReplaceAll(s, "|", `\|`) }

func code(s string) string { return "`" + s + "`" }

func surfaces(c verbs.Command) string {
	out := make([]string, len(c.Surfaces))
	for i, s := range c.Surfaces {
		out[i] = string(s)
	}
	return strings.Join(out, ", ")
}

func mode(c verbs.Command) string {
	if c.ModeNote != "" {
		return fmt.Sprintf("%s (%s)", c.Mode, c.ModeNote)
	}
	return string(c.Mode)
}

// ---- README.md -------------------------------------------------------------

func genReadme() error {
	const path = "README.md"
	b, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	s := string(b)

	var v strings.Builder
	v.WriteString("| Verb | Summary | Seat | Lane | Layers | Identity | Surfaces |\n|---|---|---|---|---|---|---|\n")
	for _, c := range verbs.Verbs {
		fmt.Fprintf(&v, "| %s | %s | %s | %s | %s | %s | %s |\n", code(c.Name), cell(c.Summary),
			verbs.SeatName(c.Seat), c.Lane, c.Layers, c.Identity, surfaces(c))
	}
	if s, err = replaceRegion(s, "verbs", v.String()); err != nil {
		return err
	}

	var p strings.Builder
	p.WriteString("| Command | Summary | Seat |\n|---|---|---|\n")
	for _, c := range verbs.Plumbing {
		fmt.Fprintf(&p, "| %s | %s | %s |\n", code(c.Name), cell(c.Summary), verbs.SeatName(c.Seat))
	}
	if s, err = replaceRegion(s, "plumbing", p.String()); err != nil {
		return err
	}
	return writeFile(path, []byte(s))
}

func replaceRegion(s, name, body string) (string, error) {
	begin := "<!-- BEGIN GENERATED: " + name + " -->"
	end := "<!-- END GENERATED: " + name + " -->"
	i := strings.Index(s, begin)
	j := strings.Index(s, end)
	if i < 0 || j < 0 || j < i || strings.Count(s, begin) != 1 || strings.Count(s, end) != 1 {
		return "", fmt.Errorf("README.md: need exactly one %q followed by one %q", begin, end)
	}
	return s[:i+len(begin)] + "\n\n" + body + "\n" + s[j:], nil
}

// ---- LAYERS.md -------------------------------------------------------------

func genLayers() error {
	var b strings.Builder
	b.WriteString(mdHeader)
	b.WriteString(`
# Layers

Generated from ` + code("internal/verbs/registry.go") + ` by ` + code("go generate ./...") + `. A changed path belongs to the
layer whose glob matches it; ` + code("slice") + ` and the screen-reader floor compute story footprints from these globs.
Each layer has exactly one owner seat. Seat charters land in WP5.1.

| Layer | Name | Owner seat | Paths |
|---|---|---|---|
`)
	for _, l := range verbs.LayerTable {
		globs := make([]string, len(l.Paths))
		for i, p := range l.Paths {
			globs[i] = code(p)
		}
		fmt.Fprintf(&b, "| %s | %s | %s | %s |\n", l.ID, cell(l.Name), verbs.SeatName(l.Owner), strings.Join(globs, "<br>"))
	}
	return writeFile("LAYERS.md", []byte(b.String()))
}

// ---- docs/RACI.md ----------------------------------------------------------

func genRACI() error {
	var b strings.Builder
	b.WriteString(mdHeader)
	b.WriteString(`
# RACI

Generated from ` + code("internal/verbs/registry.go") + ` by ` + code("go generate ./...") + `. This is the WP0.3 stub: one
Accountable seat per verb, plus the seat that owns thresholds or policy where it differs from the seat that executes.
Full Responsible / Consulted / Informed columns land in WP5.1. Every seat runs solo (agent only) or paired (agent twin
plus a human); the mode is configuration (` + code("[seats.<name>] mode") + `, WP1.2).

## Verbs

| Verb | Accountable | Owns thresholds / policy | Lane | Layers | Identity | Model calling | MCP |
|---|---|---|---|---|---|---|---|
`)
	for _, c := range verbs.Verbs {
		owns := "—"
		if c.Owns != "" {
			owns = verbs.SeatName(c.Owns)
		}
		fmt.Fprintf(&b, "| %s | %s | %s | %s | %s | %s | %s | %s |\n", code(c.Name), verbs.SeatName(c.Seat), owns,
			c.Lane, c.Layers, c.Identity, cell(mode(c)), c.Exposure)
	}

	b.WriteString(`
Model calling: ` + code("none") + ` is deterministic; ` + code("host") + ` means the host's model reasons inside the skill;
` + code("direct") + ` means the binary calls a model itself; ` + code("hybrid") + ` is host reasoning plus a direct pass
(ground rule 5). MCP: ` + code("read") + ` is exposed by default, ` + code("write") + ` only with ` + code("[mcp] expose_writes = true") + `,
` + code("never") + ` is human-only or admin (WP3.3).

## Plumbing commands

| Command | Accountable | Identity |
|---|---|---|
`)
	for _, c := range verbs.Plumbing {
		fmt.Fprintf(&b, "| %s | %s | %s |\n", code(c.Name), verbs.SeatName(c.Seat), c.Identity)
	}

	b.WriteString("\n## Seats\n\n| Seat | Slug |\n|---|---|\n")
	for _, s := range verbs.Seats {
		fmt.Fprintf(&b, "| %s | %s |\n", s.Name, code(string(s.ID)))
	}

	b.WriteString(`
## Model lanes

Settled defaults per host. Configuration (` + code("[models.<lane>.<host>]") + `, WP1.2) overrides them; the model gateway
resolves them (WP1.6). Model IDs are as the AI gateway lists them; the family belongs to the model, not the endpoint.
Cursor cannot run the openai family, so a GPT model configured for Cursor falls back to the lane's Cursor default.
When the binary calls a model itself and the host's default is a host-managed mode, it uses the Claude Code default.

` + verbs.ReviewerFamilyRule + `

| Lane | Host | Default | Model ID | Family | Escalation / alternative |
|---|---|---|---|---|---|
`)
	for _, l := range verbs.Lanes {
		for _, d := range l.Defaults {
			h, _ := verbs.FindHost(d.Host)
			model := d.Model
			if d.ContextTokens > 0 {
				model += fmt.Sprintf(" (%dk context)", d.ContextTokens/1000)
			}
			var extra []string
			if d.Escalation != "" {
				esc := "escalation: " + d.Escalation
				if d.EscalationID != "" {
					esc += " (" + code(d.EscalationID) + ")"
				}
				extra = append(extra, esc)
			}
			if d.Alternative != "" {
				extra = append(extra, "or "+d.Alternative)
			}
			if d.Note != "" {
				extra = append(extra, "note: "+d.Note)
			}
			alt := "—"
			if len(extra) > 0 {
				alt = strings.Join(extra, "; ")
			}
			name := code(string(l.ID))
			if l.Adversarial {
				name += " (adversarial)"
			}
			id := "host-managed"
			if d.ID != "" {
				id = code(d.ID)
			}
			fmt.Fprintf(&b, "| %s | %s | %s | %s | %s | %s |\n", name, h.Name, cell(model), id, d.Family, cell(alt))
		}
	}
	return writeFile("docs/RACI.md", []byte(b.String()))
}

// ---- skills/<verb>/SKILL.md ------------------------------------------------

func genSkills() error {
	want := map[string]bool{}
	for _, c := range verbs.Verbs {
		if !c.Has(verbs.SurfaceSkill) {
			continue
		}
		want[c.Name] = true
		path := filepath.Join(skillsDir, c.Name, "SKILL.md")
		body := fmt.Sprintf("\n# %s\n\n%s\n\nBody lands in %s (the verb). Format and lint: skills/README.md.\n", c.Name, c.Summary, c.WP)
		old, err := os.ReadFile(path)
		switch {
		case err == nil:
			if body, err = skillBody(string(old)); err != nil {
				return fmt.Errorf("%s: %w", path, err)
			}
		case !errors.Is(err, fs.ErrNotExist):
			return err
		}
		if err := writeFile(path, []byte("---\n"+frontmatter(c)+"---\n"+body)); err != nil {
			return err
		}
	}

	// A SKILL.md for a command without the skill surface is stale. Its body is
	// hand-authored, so refuse rather than delete it silently.
	var stale []string
	err := filepath.WalkDir(skillsDir, func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if !d.IsDir() && d.Name() == "SKILL.md" && !want[filepath.Base(filepath.Dir(path))] {
			stale = append(stale, filepath.ToSlash(path))
		}
		return nil
	})
	if err != nil {
		return err
	}
	if len(stale) > 0 {
		return fmt.Errorf("stale skills for commands without the skill surface (move or delete them): %s", strings.Join(stale, ", "))
	}
	return nil
}

// skillBody returns everything after the leading frontmatter block, verbatim.
func skillBody(s string) (string, error) {
	if !strings.HasPrefix(s, "---\n") && !strings.HasPrefix(s, "---\r\n") {
		return s, nil // no frontmatter yet: the whole file is body
	}
	rest := s[strings.Index(s, "\n")+1:]
	for off := 0; off < len(rest); {
		n := strings.Index(rest[off:], "\n")
		line, next := rest[off:], len(rest)
		if n >= 0 {
			line, next = rest[off:off+n], off+n+1
		}
		if strings.TrimSuffix(line, "\r") == "---" {
			return rest[next:], nil
		}
		off = next
	}
	return "", errors.New("frontmatter has no closing --- line")
}

// q renders s as a YAML double-quoted scalar (JSON strings are valid YAML).
func q(s string) string {
	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetEscapeHTML(false)
	_ = enc.Encode(s)
	return strings.TrimSuffix(buf.String(), "\n")
}

func yamlList(b *strings.Builder, indent, key string, items []string) {
	if len(items) == 0 {
		fmt.Fprintf(b, "%s%s: []\n", indent, key)
		return
	}
	fmt.Fprintf(b, "%s%s:\n", indent, key)
	for _, it := range items {
		fmt.Fprintf(b, "%s  - %s\n", indent, q(it))
	}
}

func frontmatter(c verbs.Command) string {
	var b strings.Builder
	b.WriteString("# " + generatedBy + "\n# Source: internal/verbs/registry.go. Only this frontmatter is generated; the body below is hand-authored.\n")
	fmt.Fprintf(&b, "name: %s\n", c.Name)
	fmt.Fprintf(&b, "description: %s\n", q(c.Summary))
	fmt.Fprintf(&b, "disable-model-invocation: %t\n", c.Exposure == verbs.ExposeNever)
	b.WriteString("user-invocable: true\n")
	if len(c.Paths) > 0 {
		yamlList(&b, "", "paths", c.Paths)
	}
	fmt.Fprintf(&b, "version: %s\n", q(verbs.SkillVersion))
	b.WriteString("aayu:\n")
	fmt.Fprintf(&b, "  seat: %s\n", c.Seat)
	fmt.Fprintf(&b, "  lane: %s\n", c.Lane)
	switch c.Layers.Scope {
	case verbs.ScopeSome:
		ids := make([]string, len(c.Layers.IDs))
		for i, id := range c.Layers.IDs {
			ids[i] = string(id)
		}
		fmt.Fprintf(&b, "  layers: [%s]\n", strings.Join(ids, ", "))
	default:
		fmt.Fprintf(&b, "  layers: %s\n", c.Layers)
	}
	if len(c.Inputs) == 0 {
		b.WriteString("  inputs: []\n")
	} else {
		b.WriteString("  inputs:\n")
		for _, in := range c.Inputs {
			fmt.Fprintf(&b, "    - name: %s\n", in.Name)
			fmt.Fprintf(&b, "      type: %s\n", in.Type)
			fmt.Fprintf(&b, "      required: %t\n", in.Required)
			fmt.Fprintf(&b, "      positional: %t\n", in.Positional)
			if len(in.Enum) > 0 {
				yamlList(&b, "      ", "enum", in.Enum)
			}
			fmt.Fprintf(&b, "      description: %s\n", q(in.Description))
		}
	}
	yamlList(&b, "  ", "outputs", c.Outputs)
	gates := make([]string, len(c.Gates))
	for i, g := range c.Gates {
		gates[i] = string(g)
	}
	yamlList(&b, "  ", "gates", gates)
	fmt.Fprintf(&b, "  identity: %s\n", c.Identity)
	fmt.Fprintf(&b, "  mode: %s\n", c.Mode)
	return b.String()
}

// ---- internal/mcp/schemas/<verb>.json --------------------------------------

func genSchemas() error {
	want := map[string]bool{}
	for _, c := range verbs.Verbs {
		if !c.Has(verbs.SurfaceMCP) {
			continue
		}
		name := c.Name + ".json"
		want[name] = true
		data, err := schema(c)
		if err != nil {
			return err
		}
		if err := writeFile(filepath.Join(schemaDir, name), data); err != nil {
			return err
		}
	}
	entries, err := os.ReadDir(schemaDir)
	if err != nil && !errors.Is(err, fs.ErrNotExist) {
		return err
	}
	for _, e := range entries {
		if !e.IsDir() && strings.HasSuffix(e.Name(), ".json") && !want[e.Name()] {
			if err := os.Remove(filepath.Join(schemaDir, e.Name())); err != nil {
				return err
			}
		}
	}
	return nil
}

func schema(c verbs.Command) ([]byte, error) {
	props := map[string]any{}
	required := []string{}
	positional := []string{}
	for _, in := range c.Inputs {
		p := map[string]any{"description": in.Description, "x-aayu-type": string(in.Type)}
		switch in.Type {
		case verbs.TypeBool:
			p["type"] = "boolean"
		case verbs.TypeInt:
			p["type"] = "integer"
		case verbs.TypeEnum:
			p["type"] = "string"
			p["enum"] = in.Enum
		case verbs.TypeIssue:
			p["type"] = "string"
			p["pattern"] = verbs.IssuePattern
		case verbs.TypePR:
			p["type"] = "string"
			p["pattern"] = verbs.PRPattern
		default:
			p["type"] = "string"
		}
		props[in.Name] = p
		if in.Required {
			required = append(required, in.Name)
		}
		if in.Positional {
			positional = append(positional, in.Name)
		}
	}
	doc := map[string]any{
		"$schema":              "https://json-schema.org/draft/2020-12/schema",
		"$comment":             generatedBy + " Source: internal/verbs/registry.go.",
		"title":                c.Name,
		"description":          c.Summary,
		"type":                 "object",
		"properties":           props,
		"required":             required,
		"additionalProperties": false,
		"x-aayu-exposure":      string(c.Exposure),
		"x-aayu-positional":    positional,
	}
	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetEscapeHTML(false)
	enc.SetIndent("", "  ")
	if err := enc.Encode(doc); err != nil { // map keys are sorted; Encode appends a newline
		return nil, err
	}
	return buf.Bytes(), nil
}

// ---- internal/config/schema.json -------------------------------------------

func genConfigSchema() error {
	data, err := config.Schema()
	if err != nil {
		return err
	}
	return writeFile(config.SchemaPath, data)
}
