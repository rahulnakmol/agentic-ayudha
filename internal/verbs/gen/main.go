// ---- skills/<verb>/SKILL.md ------------------------------------------------

func genSkills() error {
	want := map[string]bool{}
	for _, c := range verbs.Verbs {
		if !c.Has(verbs.SurfaceSkill) {
			continue
		}
		want[c.Name] = true
		path := filepath.Join(skillsDir, c.Name, "SKILL.md")
		body := fmt.Sprintf("\n# %s\n\n%s\n\nBody lands in %s (the verb). Format and lint: skills/README.md.\n", c.Name, c.Summary, c.WP)
		old, err := os.ReadFile(path)
		switch {
		case err == nil:
			if body, err = skillBody(string(old)); err != nil {
				return fmt.Errorf("%s: %w", path, err)
			}
		case !errors.Is(err, fs.ErrNotExist):
			return err
		}
		if err := writeFile(path, []byte("---\n"+frontmatter(c)+"---\n"+body)); err != nil {
			return err
		}
	}

	// A SKILL.md for a command without the skill surface is stale. Its body is
	// hand-authored, so refuse rather than delete it silently.
	var stale []string
	err := filepath.WalkDir(skillsDir, func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if !d.IsDir() && d.Name() == "SKILL.md" && !want[filepath.Base(filepath.Dir(path))] {
			stale = append(stale, filepath.ToSlash(path))
		}
		return nil
	})
	if err != nil {
		return err
	}
	if len(stale) > 0 {
		return fmt.Errorf("stale skills for commands without the skill surface (move or delete them): %s", strings.Join(stale, ", "))
	}
	return nil
}

// skillBody returns everything after the leading frontmatter block, verbatim.
func skillBody(s string) (string, error) {
	if !strings.HasPrefix(s, "---\n") && !strings.HasPrefix(s, "---\r\n") {
		return s, nil // no frontmatter yet: the whole file is body
	}
	rest := s[strings.Index(s, "\n")+1:]
	for off := 0; off < len(rest); {
		n := strings.Index(rest[off:], "\n")
		line, next := rest[off:], len(rest)
		if n >= 0 {
			line, next = rest[off:off+n], off+n+1
		}
		if strings.TrimSuffix(line, "\r") == "---" {
			return rest[next:], nil
		}
		off = next
	}
	return "", errors.New("frontmatter has no closing --- line")
}

// q renders s as a YAML double-quoted scalar (JSON strings are valid YAML).
func q(s string) string {
	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetEscapeHTML(false)
	_ = enc.Encode(s)
	return strings.TrimSuffix(buf.String(), "\n")
}

func yamlList(b *strings.Builder, indent, key string, items []string) {
	if len(items) == 0 {
		fmt.Fprintf(b, "%s%s: []\n", indent, key)
		return
	}
	fmt.Fprintf(b, "%s%s:\n", indent, key)
	for _, it := range items {
		fmt.Fprintf(b, "%s  - %s\n", indent, q(it))
	}
}

func frontmatter(c verbs.Command) string {
	var b strings.Builder
	b.WriteString("# " + generatedBy + "\n# Source: internal/verbs/registry.go. Only this frontmatter is generated; the body below is hand-authored.\n")
	fmt.Fprintf(&b, "name: %s\n", c.Name)
	fmt.Fprintf(&b, "description: %s\n", q(c.Summary))
	fmt.Fprintf(&b, "disable-model-invocation: %t\n", c.Exposure == verbs.ExposeNever)
	b.WriteString("user-invocable: true\n")
	if len(c.Paths) > 0 {
		yamlList(&b, "", "paths", c.Paths)
	}
	fmt.Fprintf(&b, "version: %s\n", q(verbs.SkillVersion))
	b.WriteString("aayu:\n")
	fmt.Fprintf(&b, "  seat: %s\n", c.Seat)
	fmt.Fprintf(&b, "  lane: %s\n", c.Lane)
	switch c.Layers.Scope {
	case verbs.ScopeSome:
		ids := make([]string, len(c.Layers.IDs))
		for i, id := range c.Layers.IDs {
			ids[i] = string(id)
		}
		fmt.Fprintf(&b, "  layers: [%s]\n", strings.Join(ids, ", "))
	default:
		fmt.Fprintf(&b, "  layers: %s\n", c.Layers)
	}
	if len(c.Inputs) == 0 {
		b.WriteString("  inputs: []\n")
	} else {
		b.WriteString("  inputs:\n")
		for _, in := range c.Inputs {
			fmt.Fprintf(&b, "    - name: %s\n", in.Name)
			fmt.Fprintf(&b, "      type: %s\n", in.Type)
			fmt.Fprintf(&b, "      required: %t\n", in.Required)
			fmt.Fprintf(&b, "      positional: %t\n", in.Positional)
			if len(in.Enum) > 0 {
				yamlList(&b, "      ", "enum", in.Enum)
			}
			fmt.Fprintf(&b, "      description: %s\n", q(in.Description))
		}
	}
	yamlList(&b, "  ", "outputs", c.Outputs)
	gates := make([]string, len(c.Gates))
	for i, g := range c.Gates {
		gates[i] = string(g)
	}
	yamlList(&b, "  ", "gates", gates)
	fmt.Fprintf(&b, "  identity: %s\n", c.Identity)
	fmt.Fprintf(&b, "  mode: %s\n", c.Mode)
	return b.String()
}

// ---- internal/mcp/schemas/<verb>.json --------------------------------------

func genSchemas() error {
	want := map[string]bool{}
	for _, c := range verbs.Verbs {
		if !c.Has(verbs.SurfaceMCP) {
			continue
		}
		name := c.Name + ".json"
		want[name] = true
		data, err := schema(c)
		if err != nil {
			return err
		}
		if err := writeFile(filepath.Join(schemaDir, name), data); err != nil {
			return err
		}
	}
	entries, err := os.ReadDir(schemaDir)
	if err != nil && !errors.Is(err, fs.ErrNotExist) {
		return err
	}
	for _, e := range entries {
		if !e.IsDir() && strings.HasSuffix(e.Name(), ".json") && !want[e.Name()] {
			if err := os.Remove(filepath.Join(schemaDir, e.Name())); err != nil {
				return err
			}
		}
	}
	return nil
}

func schema(c verbs.Command) ([]byte, error) {
	props := map[string]any{}
	required := []string{}
	positional := []string{}
	for _, in := range c.Inputs {
		p := map[string]any{"description": in.Description, "x-aayu-type": string(in.Type)}
		switch in.Type {
		case verbs.TypeBool:
			p["type"] = "boolean"
		case verbs.TypeInt:
			p["type"] = "integer"
		case verbs.TypeEnum:
			p["type"] = "string"
			p["enum"] = in.Enum
		case verbs.TypeIssue:
			p["type"] = "string"
			p["pattern"] = verbs.IssuePattern
		case verbs.TypePR:
			p["type"] = "string"
			p["pattern"] = verbs.PRPattern
		default:
			p["type"] = "string"
		}
		if in.HumanOnly {
			p["x-aayu-human-only"] = true
		}
		if len(in.ReadOnlyValues) > 0 {
			p["x-aayu-read-only-values"] = in.ReadOnlyValues
		}
		props[in.Name] = p
		if in.Required {
			required = append(required, in.Name)
		}
		if in.Positional {
			positional = append(positional, in.Name)
		}
	}
	doc := map[string]any{
		"$schema":              "https://json-schema.org/draft/2020-12/schema",
		"$comment":             generatedBy + " Source: internal/verbs/registry.go.",
		"title":                c.Name,
		"description":          c.Summary,
		"type":                 "object",
		"properties":           props,
		"required":             required,
		"additionalProperties": false,
		"x-aayu-exposure":      string(c.Exposure),
		"x-aayu-positional":    positional,
	}
	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetEscapeHTML(false)
	enc.SetIndent("", "  ")
	if err := enc.Encode(doc); err != nil { // map keys are sorted; Encode appends a newline
		return nil, err
	}
	return buf.Bytes(), nil
}

