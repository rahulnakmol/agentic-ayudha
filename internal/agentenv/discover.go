// GeneratedMarker starts the second line of every script aayu generates, so a
// hand-written one is recognised and never overwritten silently.
const GeneratedMarker = "# Generated by `aayu install --env`"

// Question is one interview question: asked only for what the code cannot
// say, with a default and the reason for it (the grill style).
type Question struct {
	ID      string   `json:"id"`
	Ask     string   `json:"ask"`
	Default string   `json:"default"`
	Why     string   `json:"why"`
	Options []string `json:"options,omitempty"`
}

// Discovery is what the code says, and the questions it leaves open.
type Discovery struct {
	Spec      Spec       `json:"spec"`
	Questions []Question `json:"questions"`
}

var (
	goLine        = regexp.MustCompile(`(?m)^go\s+([0-9][0-9.]*)\s*$`)
	toolchainLine = regexp.MustCompile(`(?m)^toolchain\s+go([0-9][0-9.]*)\s*$`)
	setupGoPin    = regexp.MustCompile(`(?m)^GO_VERSION="?([0-9][0-9.]*)"?`)
	aptInstall    = regexp.MustCompile(`apt(?:-get)?\s+install\s+([^;&|>\n]+)`)
	envLine       = regexp.MustCompile(`^\s*(?:export\s+)?([A-Z][A-Z0-9_]*)\s*=\s*(.*)$`)
	secretName    = regexp.MustCompile(`(?i)token|secret|passw|credential|api_?key|private|dsn`)
	makeTest      = regexp.MustCompile(`(?m)^test\s*:`)
	lfsAttr       = regexp.MustCompile(`filter=lfs`)
	lfsCheckout   = regexp.MustCompile(`(?m)^\s*lfs:\s*true`)
	rustChannel   = regexp.MustCompile(`(?m)^\s*channel\s*=\s*"([^"]+)"`)
)

// baseline packages the script always ensures; CI lines naming them add nothing.
var baseline = map[string]bool{"ca-certificates": true, "curl": true, "git": true, "xz-utils": true, "sudo": true, "-y": true}

type pkgJSON struct {
	Name            string            `json:"name"`
	PackageManager  string            `json:"packageManager"`
	Engines         map[string]string `json:"engines"`
	Scripts         map[string]string `json:"scripts"`
	Dependencies    map[string]string `json:"dependencies"`
	DevDependencies map[string]string `json:"devDependencies"`
	Workspaces      any               `json:"workspaces"`
}

func (p pkgJSON) has(names ...string) bool {
	for _, n := range names {
		if _, ok := p.Dependencies[n]; ok {
			return true
		}
		if _, ok := p.DevDependencies[n]; ok {
			return true
		}
	}
	return false
}

// Discover reads the repository at root and returns its environment spec,
// with every fact's evidence, and the questions only a human can answer. It
// reads files only: no network, no commands.
func Discover(root string) (Discovery, error) {
	d := &discoverer{root: root, spec: Spec{Version: 1, Hosts: append([]string(nil), Hosts...), Answers: map[string]Answer{}}}
	d.goModule()
	d.node()
	d.python()
	d.rust()
	d.services()
	d.envFile()
	d.systemPackages()
	d.makefile()
	d.unsupported()
	d.existingSetup()
	if len(d.spec.Checks) == 0 {
		d.ask(Question{ID: "checks", Ask: "The code names no build or test command. Which command proves an agent can work here?",
			Default: "none", Why: "without one, verification can only show that setup succeeds"})
	}
	d.ask(Question{ID: "hosts", Ask: "Which agent hosts should get an environment?", Default: strings.Join(Hosts, ","),
		Why: "one spec generates all four; a host's files do nothing until that host is used", Options: Hosts})
	sort.Strings(d.spec.Packages)
	return Discovery{Spec: d.spec, Questions: d.questions}, nil
}

type discoverer struct {
	root      string
	spec      Spec
	questions []Question
	envNames  map[string]bool
}

func (d *discoverer) read(rel string) []byte {
	b, _ := os.ReadFile(filepath.Join(d.root, filepath.FromSlash(rel)))
	return b
}

func (d *discoverer) exists(rel string) bool {
	_, err := os.Stat(filepath.Join(d.root, filepath.FromSlash(rel)))
	return err == nil
}

func (d *discoverer) ask(q Question) { d.questions = append(d.questions, q) }

func (d *discoverer) pkg(name string) {
	for _, p := range d.spec.Packages {
		if p == name {
			return
		}
	}
	d.spec.Packages = append(d.spec.Packages, name)
}

func (d *discoverer) check(run, ev string) {
	for _, c := range d.spec.Checks {
		if c.Run == run {
			return
		}
	}
	d.spec.Checks = append(d.spec.Checks, Step{Run: run, Evidence: ev})
}

func (d *discoverer) service(name, ev string) {
	for i, s := range d.spec.Services {
		if s.Name == name {
			if !strings.Contains(s.Evidence, ev) {
				d.spec.Services[i].Evidence += "; " + ev
			}
			return
		}
	}
	d.spec.Services = append(d.spec.Services, Service{Name: name, Evidence: ev})
}

func lineOf(b []byte, re *regexp.Regexp) int {
	loc := re.FindIndex(b)
	if loc == nil {
		return 0
	}
	return strings.Count(string(b[:loc[0]]), "\n") + 1
}

func (d *discoverer) goModule() {
	mod := d.read("go.mod")
	m := goLine.FindSubmatch(mod)
	if m == nil {
		return
	}
	floor := string(m[1])
	t := Tool{Name: "go", Want: ">=" + floor, Evidence: fmt.Sprintf("go.mod:%d (go %s)", lineOf(mod, goLine), floor)}
	if tc := toolchainLine.FindSubmatch(mod); tc != nil {
		t.Want, t.Version = "toolchain "+string(tc[1]), string(tc[1])
		t.Evidence += fmt.Sprintf("; go.mod:%d (toolchain go%s)", lineOf(mod, toolchainLine), tc[1])
	}
	d.spec.Tools = append(d.spec.Tools, t)
	ev := "go.mod"
	if d.exists("go.sum") {
		ev = "go.sum"
	}
	d.spec.Deps = append(d.spec.Deps, Step{Run: "go mod download", Evidence: ev})
	d.check("go build ./...", "go.mod")
	d.check("go test ./...", "go.mod")
	for _, dep := range []struct{ mod, svc string }{{"github.com/jackc/pgx", "postgres"}, {"github.com/lib/pq", "postgres"}, {"github.com/redis/go-redis", "redis"}, {"github.com/go-redis/redis", "redis"}, {"github.com/go-sql-driver/mysql", "mysql"}} {
		if strings.Contains(string(mod), dep.mod) {
			d.service(dep.svc, "go.mod requires "+dep.mod)
		}
	}
}

func (d *discoverer) node() {
	b := d.read("package.json")
	if b == nil {
		return
	}
	var root pkgJSON
	if err := json.Unmarshal(b, &root); err != nil {
		d.spec.Notes = append(d.spec.Notes, "package.json does not parse ("+err.Error()+"); Node is not set up")
		return
	}
	pm, pmVer, pmEv := "", "", ""
	if name, ver, ok := strings.Cut(root.PackageManager, "@"); ok {
		pm, pmVer, pmEv = name, strings.SplitN(ver, "+", 2)[0], "package.json packageManager ("+root.PackageManager+")"
	}
	switch {
	case pm != "":
	case d.exists("pnpm-lock.yaml"):
		pm, pmEv = "pnpm", "pnpm-lock.yaml"
	case d.exists("yarn.lock"):
		pm, pmEv = "yarn", "yarn.lock"
	case d.exists("bun.lock") || d.exists("bun.lockb"):
		pm, pmEv = "bun", "bun.lock"
	default:
		pm, pmEv = "npm", "package.json"
	}
	node := Tool{Name: "node", Want: "lts", Evidence: "package.json (no engines.node: the current LTS)"}
	if e := root.Engines["node"]; e != "" {
		node.Want, node.Evidence = e, "package.json engines.node ("+e+")"
	} else if v := strings.TrimSpace(string(d.read(".nvmrc")) + string(d.read(".node-version"))); v != "" {
		node.Want, node.Evidence = strings.TrimPrefix(strings.Fields(v)[0], "v"), ".nvmrc"
	}
	d.spec.Tools = append(d.spec.Tools, node)
	switch pm {
	case "pnpm", "yarn":
		d.spec.Tools = append(d.spec.Tools, Tool{Name: pm, Want: orStr(pmVer, "corepack default"), Version: pmVer, Via: "corepack", Evidence: pmEv})
	case "bun":
		d.spec.Notes = append(d.spec.Notes, "bun ("+pmEv+") is not installed by aayu yet; add its install as a step, and note Claude Code's cloud proxy breaks Bun's package fetching (code.claude.com/docs/en/cloud-environments)")
	}
	lock := map[string]string{"pnpm": "pnpm install --frozen-lockfile", "yarn": "yarn install --immutable", "npm": "npm ci"}
	if pm == "yarn" && !strings.HasPrefix(pmVer, "1.") && pmVer != "" {
		lock["yarn"] = "yarn install --immutable"
	} else if pm == "yarn" {
		lock["yarn"] = "yarn install --frozen-lockfile"
	}
	if pm == "npm" && !d.exists("package-lock.json") {
		lock["npm"] = "npm install"
	}
	if run, ok := lock[pm]; ok {
		d.spec.Deps = append(d.spec.Deps, Step{Run: run, Evidence: pmEv})
	}
	pkgs := []pkgJSON{root}
	ws := d.workspaces(root)
	for _, w := range ws {
		var p pkgJSON
		if json.Unmarshal(d.read(w+"/package.json"), &p) == nil {
			pkgs = append(pkgs, p)
		}
	}
	for _, script := range []string{"build", "test"} {
		if _, ok := root.Scripts[script]; ok {
			d.check(pm+" run "+script, "package.json scripts."+script)
			continue
		}
		var in []string
		for i, p := range pkgs[1:] {
			if _, ok := p.Scripts[script]; ok {
				in = append(in, ws[i])
			}
		}
		if len(in) == 0 {
			continue
		}
		ev := "scripts." + script + " in " + strings.Join(in, ", ")
		switch pm {
		case "pnpm":
			d.check("pnpm -r --if-present run "+script, ev)
		case "npm":
			d.check("npm run "+script+" --workspaces --if-present", ev)
		case "yarn":
			d.check("yarn workspaces foreach -A run "+script, ev)
		}
	}
	for i, p := range pkgs {
		where := "package.json"
		if i > 0 {
			where = ws[i-1] + "/package.json"
		}
		if p.has("playwright", "@playwright/test") && len(d.spec.Browsers) == 0 {
			run := map[string]string{"pnpm": "pnpm exec", "npm": "npx --no-install", "yarn": "yarn"}[pm]
			if i > 0 && pm == "pnpm" {
				run = "pnpm --filter " + p.Name + " exec"
			} else if i > 0 && pm == "npm" {
				run = "npm exec -w " + ws[i-1] + " --"
			}
			if run != "" {
				d.ask(Question{ID: "browsers", Ask: fmt.Sprintf("%s depends on Playwright. Install Chromium (and its system libraries) in every agent environment?", where),
					Default: "yes", Why: "browser tests and UI proof cannot run without it; it adds about 150 MB and a minute or two to a cold setup", Options: []string{"yes", "no"}})
				d.spec.Browsers = []Step{{Run: run + " playwright install --with-deps chromium", Evidence: where + " depends on playwright"}}
			}
		}
		for _, dep := range []struct {
			svc   string
			names []string
		}{{"postgres", []string{"pg", "postgres", "pg-promise"}}, {"redis", []string{"redis", "ioredis"}}, {"mysql", []string{"mysql", "mysql2"}}} {
			if p.has(dep.names...) {
				d.service(dep.svc, where+" depends on "+strings.Join(dep.names, " or "))
			}
		}
	}
}

// workspaces lists workspace package directories (pnpm-workspace.yaml globs or
// package.json workspaces), one level of "dir/*" globs.
func (d *discoverer) workspaces(root pkgJSON) []string {
	var globs []string
	if b := d.read("pnpm-workspace.yaml"); b != nil {
		in := false
		for _, l := range strings.Split(string(b), "\n") {
			t := strings.TrimSpace(l)
			switch {
			case strings.HasPrefix(l, "packages:"):
				in = true
			case in && strings.HasPrefix(t, "- "):
				globs = append(globs, strings.Trim(strings.TrimPrefix(t, "- "), `"'`))
			case in && t != "" && !strings.HasPrefix(t, "#"):
				in = false
			}
		}
	}
	switch w := root.Workspaces.(type) {
	case []any:
		for _, g := range w {
			if s, ok := g.(string); ok {
				globs = append(globs, s)
			}
		}
	}
	var out []string
	for _, g := range globs {
		ms, _ := filepath.Glob(filepath.Join(d.root, filepath.FromSlash(g), "package.json"))
		for _, m := range ms {
			rel, _ := filepath.Rel(d.root, filepath.Dir(m))
			out = append(out, filepath.ToSlash(rel))
		}
	}
	sort.Strings(out)
	return out
}

func (d *discoverer) python() {
	py := d.read("pyproject.toml")
	req := d.read("requirements.txt")
	if py == nil && req == nil {
		return
	}
	var proj struct {
		Project struct {
			RequiresPython string   `toml:"requires-python"`
			Dependencies   []string `toml:"dependencies"`
		} `toml:"project"`
		DependencyGroups map[string][]any `toml:"dependency-groups"`
	}
	_ = toml.Unmarshal(py, &proj)
	all := strings.ToLower(string(py) + "\n" + string(req))
	want, ev := orStr(proj.Project.RequiresPython, "3"), "pyproject.toml requires-python"
	if v := strings.TrimSpace(string(d.read(".python-version"))); v != "" {
		want, ev = v, ".python-version"
	}
	switch {
	case d.exists("uv.lock") || (py != nil && req == nil && !d.exists("poetry.lock")):
		d.spec.Tools = append(d.spec.Tools, Tool{Name: "uv", Want: "latest", Via: "tarball", Evidence: orStr(map[bool]string{true: "uv.lock"}[d.exists("uv.lock")], "pyproject.toml (no other lockfile: uv)")})
		d.spec.Tools = append(d.spec.Tools, Tool{Name: "python", Want: want, Via: "uv", Evidence: ev})
		run := "uv sync --frozen"
		if !d.exists("uv.lock") {
			run = "uv sync"
		}
		d.spec.Deps = append(d.spec.Deps, Step{Run: run, Evidence: "pyproject.toml"})
		if strings.Contains(all, "pytest") {
			d.check("uv run pytest", "pytest in pyproject.toml")
		}
	case d.exists("poetry.lock"):
		d.spec.Notes = append(d.spec.Notes, "poetry.lock: aayu does not install Poetry yet; add `pipx install poetry && poetry install` as a step")
	default:
		d.spec.Tools = append(d.spec.Tools, Tool{Name: "python", Want: want, Via: "apt", Evidence: ev})
		d.pkg("python3")
		d.pkg("python3-venv")
		d.spec.Deps = append(d.spec.Deps, Step{Run: "python3 -m venv .venv && .venv/bin/pip install -q -r requirements.txt", Evidence: "requirements.txt"})
		if strings.Contains(all, "pytest") {
			d.check(".venv/bin/python -m pytest", "pytest in requirements.txt")
		}
	}
	for _, dep := range []struct {
		svc   string
		names []string
	}{{"postgres", []string{"psycopg", "asyncpg"}}, {"redis", []string{"redis"}}, {"mysql", []string{"pymysql", "mysqlclient"}}} {
		for _, n := range dep.names {
			if regexp.MustCompile(`(?m)["\s^]` + n + `[\w-]*\s*([<>=~\[;"]|$)`).MatchString(all) {
				d.service(dep.svc, "Python dependency "+n)
				break
			}
		}
	}
	if regexp.MustCompile(`(?m)["\s^]playwright\s*([<>=~;"]|$)`).MatchString(all) && len(d.spec.Browsers) == 0 {
		run := "uv run playwright install --with-deps chromium"
		if d.spec.Tool("uv") == nil {
			run = ".venv/bin/python -m playwright install --with-deps chromium"
		}
		d.spec.Browsers = []Step{{Run: run, Evidence: "Python dependency playwright"}}
		d.ask(Question{ID: "browsers", Ask: "The Python dependencies include Playwright. Install Chromium (and its system libraries) in every agent environment?",
			Default: "yes", Why: "browser tests cannot run without it", Options: []string{"yes", "no"}})
	}
}

func (d *discoverer) rust() {
	if !d.exists("Cargo.toml") {
		return
	}
	want, ev := "stable", "Cargo.toml (no rust-toolchain file: stable)"
	for _, f := range []string{"rust-toolchain.toml", "rust-toolchain"} {
		if b := d.read(f); b != nil {
			if m := rustChannel.FindSubmatch(b); m != nil {
				want = string(m[1])
			} else if t := strings.TrimSpace(string(b)); t != "" && !strings.Contains(t, "[") {
				want = t
			}
			ev = f
		}
	}
	d.spec.Tools = append(d.spec.Tools, Tool{Name: "rust", Want: want, Via: "rustup", Evidence: ev})
	d.pkg("build-essential")
	locked := ""
	if d.exists("Cargo.lock") {
		locked = " --locked"
	}
	d.spec.Deps = append(d.spec.Deps, Step{Run: "cargo fetch" + locked, Evidence: "Cargo.toml"})
	d.check("cargo build"+locked, "Cargo.toml")
	d.check("cargo test"+locked, "Cargo.toml")
}

func (d *discoverer) services() {
	for _, f := range []string{"docker-compose.yml", "docker-compose.yaml", "compose.yml", "compose.yaml"} {
		b := d.read(f)
		if b == nil {
			continue
		}
		for _, img := range regexp.MustCompile(`(?m)^\s*image:\s*["']?([^\s"']+)`).FindAllSubmatch(b, -1) {
			name := strings.ToLower(string(img[1]))
			name = name[strings.LastIndex(name, "/")+1:]
			name, _, _ = strings.Cut(name, ":")
			switch name {
			case "postgres", "postgis", "pgvector":
				d.service("postgres", f+" image "+string(img[1]))
			case "redis", "valkey":
				d.service("redis", f+" image "+string(img[1]))
			case "mysql", "mariadb":
				d.service("mysql", f+" image "+string(img[1]))
			default:
				d.spec.Notes = append(d.spec.Notes, fmt.Sprintf("%s runs image %s, which aayu does not install natively; agents that need it run it with Docker where the host offers Docker", f, img[1]))
			}
		}
	}
}

func (d *discoverer) envFile() {
	d.envNames = map[string]bool{}
	for _, f := range []string{".env.example", ".env.sample", ".env.template", ".env.dist"} {
		b := d.read(f)
		if b == nil {
			continue
		}
		target := ".env"
		if strings.Contains(string(d.read(".gitignore")), ".env.local") {
			target = ".env.local"
		}
		d.spec.EnvFile = f + " -> " + target
		sc := bufio.NewScanner(strings.NewReader(string(b)))
		for n := 1; sc.Scan(); n++ {
			m := envLine.FindStringSubmatch(sc.Text())
			if m == nil || d.envNames[m[1]] {
				continue
			}
			d.envNames[m[1]] = true
			ev := fmt.Sprintf("%s:%d", f, n)
			d.spec.Env = append(d.spec.Env, EnvVar{Name: m[1], Secret: secretName.MatchString(m[1]) && !isURLOnLocalhost(m[2]), Evidence: ev})
			val := strings.Trim(strings.TrimSpace(m[2]), `"'`)
			if u, err := url.Parse(val); err == nil && u.Host != "" {
				svc := map[string]string{"postgres": "postgres", "postgresql": "postgres", "redis": "redis", "rediss": "redis", "mysql": "mysql"}[u.Scheme]
				if svc == "" {
					continue
				}
				d.service(svc, ev+" "+m[1])
				for i := range d.spec.Services {
					if s := &d.spec.Services[i]; s.Name == svc && s.User == "" && svc != "redis" {
						s.User = u.User.Username()
						s.Password, _ = u.User.Password()
						s.Database = strings.TrimPrefix(u.Path, "/")
					}
				}
			}
		}
		break
	}
	var secrets []string
	for _, e := range d.spec.Env {
		if e.Secret {
			secrets = append(secrets, e.Name)
		}
	}
	if len(secrets) > 0 {
		d.ask(Question{ID: "secrets", Ask: fmt.Sprintf("%s names secrets: %s. Do the build or tests need real values for any of them? Name them, or say none.", strings.Split(d.spec.EnvFile, " ")[0], strings.Join(secrets, ", ")),
			Default: "none", Why: "agent environments get no long-lived secrets (research §6.3); the placeholders in the example file are used"})
	}
}

func isURLOnLocalhost(v string) bool {
	u, err := url.Parse(strings.Trim(strings.TrimSpace(v), `"'`))
	return err == nil && (u.Hostname() == "localhost" || u.Hostname() == "127.0.0.1")
}

func (d *discoverer) systemPackages() {
	if lfsAttr.Match(d.read(".gitattributes")) {
		d.pkg("git-lfs")
	}
	files, _ := filepath.Glob(filepath.Join(d.root, ".github", "workflows", "*.y*ml"))
	for _, f := range files {
		b, _ := os.ReadFile(f)
		rel := ".github/workflows/" + filepath.Base(f)
		if lfsCheckout.Match(b) {
			d.pkg("git-lfs")
		}
		for _, m := range aptInstall.FindAllSubmatch(b, -1) {
			for _, p := range strings.Fields(string(m[1])) {
				if strings.HasPrefix(p, "-") || strings.ContainsAny(p, "$={}") || baseline[p] {
					continue
				}
				d.pkg(p)
				d.addEvidence("packages", p+" ("+rel+")")
			}
		}
	}
}

// addEvidence records where a package came from in Notes (packages are plain strings).
func (d *discoverer) addEvidence(kind, what string) {
	n := "apt package " + what
	for _, x := range d.spec.Notes {
		if x == n {
			return
		}
	}
	d.spec.Notes = append(d.spec.Notes, n)
}

func (d *discoverer) makefile() {
	if b := d.read("Makefile"); makeTest.Match(b) {
		d.spec.Checks = []Step{{Run: "make test", Evidence: fmt.Sprintf("Makefile:%d (test target)", lineOf(b, makeTest))}}
		d.pkg("make")
	}
}

func (d *discoverer) unsupported() {
	var found []string
	for f, what := range map[string]string{"Gemfile": "Ruby", "pom.xml": "Java (Maven)", "build.gradle": "Java (Gradle)", "build.gradle.kts": "Kotlin (Gradle)", "composer.json": "PHP", "mix.exs": "Elixir", "Package.swift": "Swift"} {
		if d.exists(f) {
			found = append(found, what+" ("+f+")")
		}
	}
	if len(found) == 0 {
		return
	}
	sort.Strings(found)
	d.ask(Question{ID: "steps", Ask: "aayu does not install " + strings.Join(found, ", ") + " yet. Which setup command installs it (one shell line), or skip?",
		Default: "skip", Why: "a toolchain aayu cannot pin is better written once as a step than missed"})
}

func (d *discoverer) existingSetup() {
	b := d.read(SetupPath)
	if b == nil || strings.Contains(string(b), GeneratedMarker) {
		return
	}
	if m := setupGoPin.FindSubmatch(b); m != nil {
		if g := d.spec.Tool("go"); g != nil && g.Version == "" {
			floor := strings.TrimPrefix(g.Want, ">=")
			if !olderVersion(string(m[1]), floor) {
				d.ask(Question{ID: "go-version", Ask: fmt.Sprintf("Your hand-written %s pins Go %s; go.mod asks for at least %s. Which Go should every agent environment install?", SetupPath, m[1], floor),
					Default: string(m[1]), Why: "keeps the toolchain the team already runs; newer than go.mod's floor is allowed (Appendix B D5)"})
			}
		}
	}
	d.ask(Question{ID: "existing-setup", Ask: fmt.Sprintf("%s was written by hand. Replace it with the generated script (the diff shows every change)?", SetupPath),
		Default: "replace", Why: "every host calls one generated script, so a pin changes in one place; keep it only if it does something the spec cannot say", Options: []string{"replace", "keep"}})
}

func orStr(a, b string) string {
	if a != "" {
		return a
	}
	return b
}

// olderVersion reports whether dotted version a is older than b.
func olderVersion(a, b string) bool {
	as, bs := strings.Split(a, "."), strings.Split(b, ".")
	for i := 0; i < max(len(as), len(bs)); i++ {
		var x, y int
		if i < len(as) {
			x, _ = strconv.Atoi(as[i])
		}
		if i < len(bs) {
			y, _ = strconv.Atoi(bs[i])
		}
		if x != y {
			return x < y
		}
	}
	return false
}
