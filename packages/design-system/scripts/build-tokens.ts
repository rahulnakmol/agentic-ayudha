// Generates the platform token exports from tokens/tokens.json (WP6.1, WP6.3):
//   src/styles/tokens.css                   CSS custom properties (--ay-*), density modes as [data-density]
//   platforms/swiftui/AyudhaTokens.swift    SwiftUI (iOS 17 / macOS 14)
//   platforms/compose/AyudhaTokens.kt       Jetpack Compose
//
// Naming rule (the same on every platform): a token path such as color.text.label becomes
// `--ay-color-text-label` in CSS and `colorTextLabel` in Swift and Kotlin. Density-mode tokens drop the
// mode from the name (`density.compact.size.row-height` -> `--ay-size-row-height` under
// [data-density="compact"], `sizeRowHeight` on `densityCompact`). The `web` group is web-only.
//
// Usage: node scripts/build-tokens.ts           write the files
//        node scripts/build-tokens.ts --check   exit 1 if any file is out of date
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

type Token = { $type: string; $value: unknown; $description?: string };
type Group = { [key: string]: Group | Token | string };
type Flat = { path: string[]; token: Token };

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const source = JSON.parse(readFileSync(join(root, "tokens/tokens.json"), "utf8")) as Group;
const HEADER = "Generated by packages/design-system/scripts/build-tokens.ts from tokens/tokens.json. Do not edit.";

function flatten(group: Group, prefix: string[] = []): Flat[] {
  const out: Flat[] = [];
  for (const [key, value] of Object.entries(group)) {
    if (key.startsWith("$") || typeof value === "string") continue;
    if ("$value" in value) out.push({ path: [...prefix, key], token: value as Token });
    else out.push(...flatten(value as Group, [...prefix, key]));
  }
  return out;
}

const kebab = (path: string[]) => path.join("-");
const camel = (path: string[]) =>
  kebab(path).replace(/-([a-z0-9])/g, (_, c: string) => c.toUpperCase());
const cap = (s: string) => s[0].toUpperCase() + s.slice(1);
const num = (n: number) => String(Number(n.toFixed(4)));

const { density, web, ...shared } = source as Record<string, Group>;
const sharedTokens = flatten(shared);
const modes = Object.keys(density).filter((k) => !k.startsWith("$"));
const modeTokens = Object.fromEntries(modes.map((m) => [m, flatten(density[m] as Group)]));
const webTokens = flatten(web as Group);

// Every density mode must define exactly the same names, or the platforms would diverge.
const modeNames = modes.map((m) => modeTokens[m].map((t) => camel(t.path)).join(","));
if (new Set(modeNames).size !== 1) throw new Error(`density modes define different tokens: ${modes.join(", ")}`);
const densityFields = modeTokens[modes[0]];

function hex(value: unknown): { rgb: string; alpha: string } {
  const v = String(value).toLowerCase();
  if (!/^#([0-9a-f]{6}|[0-9a-f]{8})$/.test(v)) throw new Error(`colour must be #rrggbb or #rrggbbaa: ${v}`);
  return { rgb: v.slice(1, 7), alpha: v.length === 9 ? v.slice(7, 9) : "ff" };
}

// ---------------------------------------------------------------- CSS
function cssValue(t: Token): string {
  const v = t.$value;
  switch (t.$type) {
    case "color":
      return String(v).toLowerCase();
    case "dimension":
      return `${num((v as number) / 16)}rem`;
    case "duration":
      return `${v}ms`;
    case "cubicBezier":
      return `cubic-bezier(${(v as number[]).map(num).join(", ")})`;
    case "fontWeight":
    case "fontFamily":
      return String(v);
    default:
      throw new Error(`unsupported token type ${t.$type}`);
  }
}

function css(): string {
  const decl = (t: Flat) => `  --ay-${kebab(t.path)}: ${cssValue(t.token)};`;
  const blocks = [
    `/* ${HEADER} */\n:root {\n${[...sharedTokens, ...webTokens].map(decl).join("\n")}\n}`,
    ...modes.map((m, i) => {
      const selector = i === 0 ? `:root,\n[data-density="${m}"]` : `[data-density="${m}"]`;
      return `${selector} {\n${modeTokens[m].map(decl).join("\n")}\n}`;
    }),
  ];
  return blocks.join("\n\n") + "\n";
}

// ---------------------------------------------------------------- SwiftUI
const swiftWeight: Record<number, string> = {
  100: "ultraLight", 200: "thin", 300: "light", 400: "regular", 500: "medium",
  600: "semibold", 700: "bold", 800: "heavy", 900: "black",
};

function swiftValue(t: Token): { type?: string; expr: string } {
  const v = t.$value;
  switch (t.$type) {
    case "color": {
      const { rgb, alpha } = hex(v);
      return { expr: `Color(ayudhaHex: 0x${rgb.toUpperCase()}, alpha: 0x${alpha.toUpperCase()})` };
    }
    case "dimension":
      return { type: "CGFloat", expr: num(v as number) };
    case "duration":
      return { type: "TimeInterval", expr: num((v as number) / 1000) };
    case "cubicBezier": {
      const [x1, y1, x2, y2] = (v as number[]).map(num);
      return {
        expr: `UnitCurve.bezier(startControlPoint: UnitPoint(x: ${x1}, y: ${y1}), endControlPoint: UnitPoint(x: ${x2}, y: ${y2}))`,
      };
    }
    case "fontWeight": {
      const w = swiftWeight[v as number];
      if (!w) throw new Error(`no SwiftUI weight for ${v}`);
      return { expr: `Font.Weight.${w}` };
    }
    default:
      throw new Error(`unsupported token type ${t.$type}`);
  }
}

const doc = (t: Token, indent: string, style: "swift" | "kotlin") =>
  t.$description ? `${indent}${style === "swift" ? "///" : "/**"} ${t.$description}${style === "kotlin" ? " */" : ""}\n` : "";

function swift(): string {
  const lines = sharedTokens.map(({ path, token }) => {
    const { type, expr } = swiftValue(token);
    return `${doc(token, "    ", "swift")}    public static let ${camel(path)}${type ? `: ${type}` : ""} = ${expr}`;
  });
  const fields = densityFields.map(({ path, token }) => {
    const { type } = swiftValue(token);
    return `${doc(token, "        ", "swift")}        public let ${camel(path)}: ${type}`;
  });
  const instances = modes.map((m) => {
    const args = modeTokens[m].map(({ path, token }) => `${camel(path)}: ${swiftValue(token).expr}`).join(", ");
    return `    public static let density${cap(m)} = DensityTokens(${args})`;
  });
  return `// ${HEADER}
// Dimensions are points, durations are seconds. Requires iOS 17 / macOS 14 (UnitCurve).
import SwiftUI

public enum AyudhaTokens {
${lines.join("\n")}

    /// Density-dependent tokens. Every mode defines the same fields.
    public struct DensityTokens: Sendable {
${fields.join("\n")}
    }

${instances.join("\n")}
}

extension Color {
    /// 0xRRGGBB plus a separate 0x00–0xFF alpha, in sRGB.
    init(ayudhaHex rgb: UInt32, alpha: UInt32) {
        self.init(
            .sRGB,
            red: Double((rgb >> 16) & 0xFF) / 255,
            green: Double((rgb >> 8) & 0xFF) / 255,
            blue: Double(rgb & 0xFF) / 255,
            opacity: Double(alpha) / 255
        )
    }
}
`;
}

// ---------------------------------------------------------------- Compose
function kotlinValue(t: Token): { type?: string; expr: string; isConst?: boolean } {
  const v = t.$value;
  const f = (n: number) => `${num(n)}f`;
  switch (t.$type) {
    case "color": {
      const { rgb, alpha } = hex(v);
      return { expr: `Color(0x${(alpha + rgb).toUpperCase()})` };
    }
    case "dimension":
      // Font sizes are text units (sp) so they follow the user's font scale; everything else is dp.
      return { type: "Dp", expr: `${num(v as number)}.dp` };
    case "duration":
      return { expr: String(v), isConst: true };
    case "cubicBezier":
      return { expr: `CubicBezierEasing(${(v as number[]).map(f).join(", ")})` };
    case "fontWeight":
      return { expr: `FontWeight(${v})` };
    default:
      throw new Error(`unsupported token type ${t.$type}`);
  }
}

function kotlinExpr(path: string[], token: Token) {
  const value = kotlinValue(token);
  if (path[0] === "font" && path[1] === "size") return { ...value, type: "TextUnit", expr: `${num(token.$value as number)}.sp` };
  return value;
}

function kotlin(): string {
  const lines = sharedTokens.map(({ path, token }) => {
    const { expr, isConst } = kotlinExpr(path, token);
    const unit = token.$type === "duration" ? " // milliseconds" : "";
    return `${doc(token, "    ", "kotlin")}    ${isConst ? "const val" : "val"} ${camel(path)} = ${expr}${unit}`;
  });
  const fields = densityFields.map(({ path, token }) => {
    return `${doc(token, "        ", "kotlin")}        val ${camel(path)}: ${kotlinExpr(path, token).type},`;
  });
  const instances = modes.map((m) => {
    const args = modeTokens[m].map(({ path, token }) => `${camel(path)} = ${kotlinExpr(path, token).expr}`).join(", ");
    return `    val density${cap(m)} = DensityTokens(${args})`;
  });
  return `// ${HEADER}
// Dimensions are dp (font sizes sp), durations are milliseconds.
package dev.aayudha.designsystem

import androidx.compose.animation.core.CubicBezierEasing
import androidx.compose.ui.graphics.Color
import androidx.compose.ui.text.font.FontWeight
import androidx.compose.ui.unit.Dp
import androidx.compose.ui.unit.TextUnit
import androidx.compose.ui.unit.dp
import androidx.compose.ui.unit.sp

object AyudhaTokens {
${lines.join("\n")}

    /** Density-dependent tokens. Every mode defines the same fields. */
    data class DensityTokens(
${fields.join("\n")}
    )

${instances.join("\n")}
}
`;
}

// ---------------------------------------------------------------- write / check
const outputs: Record<string, string> = {
  "src/styles/tokens.css": css(),
  "platforms/swiftui/AyudhaTokens.swift": swift(),
  "platforms/compose/AyudhaTokens.kt": kotlin(),
};

const check = process.argv.includes("--check");
let stale = 0;
for (const [file, content] of Object.entries(outputs)) {
  const path = join(root, file);
  let current = "";
  try {
    current = readFileSync(path, "utf8");
  } catch {}
  if (current === content) continue;
  if (check) {
    console.error(`out of date: packages/design-system/${file}`);
    stale++;
  } else {
    writeFileSync(path, content);
    console.log(`wrote packages/design-system/${file}`);
  }
}
if (stale) {
  console.error("Run `pnpm --filter @aayudha/design-system tokens` and commit the result.");
  process.exit(1);
}
